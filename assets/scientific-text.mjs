import katex from './vendor/katex/katex.mjs';
import './vendor/katex/contrib/mhchem.mjs';

const mathCache = new Map();
const textCache = new Map();
const CACHE_LIMIT = 512;
const MAX_MATH_LENGTH = 2000;
const bareCommands = new Set(['ce', 'bar', 'overline', 'hat', 'vec']);
const subscript = Object.fromEntries([...('0123456789+-=()')].map((c,i)=>[c,[...'₀₁₂₃₄₅₆₇₈₉₊₋₌₍₎'][i]]));
const superscript = Object.fromEntries([...('0123456789+-=()n')].map((c,i)=>[c,[...'⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻⁼⁽⁾ⁿ'][i]]));

function cachePut(cache, key, value){
  if(cache.size >= CACHE_LIMIT) cache.delete(cache.keys().next().value);
  cache.set(key,value);
  return value;
}
function escapedAt(text, index){
  let slashes=0;
  for(let i=index-1;i>=0 && text[i]==='\\';i--) slashes++;
  return slashes%2===1;
}
function readGroup(text, index){
  while(/\s/.test(text[index]||'') && index<text.length) index++;
  if(text[index]!=='{') return null;
  let depth=1;
  for(let i=index+1;i<text.length;i++){
    if(escapedAt(text,i)) continue;
    if(text[i]==='{') depth++;
    else if(text[i]==='}' && --depth===0) return {value:text.slice(index+1,i),end:i+1};
  }
  return null;
}

// Keep TeX's visual branch; the second branch is only a PDF bookmark fallback.
function prepareText(value){
  const text=String(value??'');
  let result='', position=0;
  const command=/\\texorpdfstring\b/g;
  for(let match; (match=command.exec(text));){
    if(escapedAt(text,match.index)) continue;
    const first=readGroup(text,command.lastIndex);
    const second=first && readGroup(text,first.end);
    if(!second) continue;
    result+=text.slice(position,match.index)+first.value;
    position=second.end;
    command.lastIndex=second.end;
  }
  return result+text.slice(position);
}
function isCurrencyStart(text, index){
  return /^\d[\d,.]*(?:\s+(?:million|billion|trillion|dollars?|USD)\b)/i.test(text.slice(index+1));
}

export function splitScientificText(value, {prepare=true}={}){
  const text=prepare?prepareText(value):String(value??'');
  const tokens=[];
  let start=0, i=0;
  const pushMath=(end,body,display=false)=>{
    if(i>start) tokens.push({type:'text',value:text.slice(start,i)});
    tokens.push({type:'math',value:body,raw:text.slice(i,end),display});
    i=end;start=end;
  };
  while(i<text.length){
    if(escapedAt(text,i)){i++;continue;}
    let open='',close='',display=false;
    if(text.startsWith('\\(',i)){open='\\(';close='\\)';}
    else if(text.startsWith('\\[',i)){open='\\[';close='\\]';display=true;}
    else if(text[i]==='$' && !isCurrencyStart(text,i)){
      open=text.startsWith('$$',i)?'$$':'$';close=open;display=open==='$$';
    }
    if(open){
      let end=text.indexOf(close,i+open.length);
      while(end!==-1 && escapedAt(text,end)) end=text.indexOf(close,end+close.length);
      if(end===-1) break; // Preserve a truncated RSS formula as source text.
      if(end!==-1){
        const body=text.slice(i+open.length,end);
        if(body.trim()){pushMath(end+close.length,body,display);continue;}
      }
    }
    if(text[i]==='\\'){
      const command=/^\\([A-Za-z]+)/.exec(text.slice(i));
      if(command && bareCommands.has(command[1])){
        const group=readGroup(text,i+command[0].length);
        if(group){pushMath(group.end,text.slice(i,group.end));continue;}
      }
    }
    i++;
  }
  if(start<text.length) tokens.push({type:'text',value:text.slice(start)});
  return tokens;
}

function displayText(value){
  let text=value.replace(/\{\s*\\deg\s*\}/g,'°').replace(/\\AA\b/g,'Å').replace(/^~(?=[A-Za-zÅ])/,'\u00a0').replace(/\\([%&#_$])/g,'$1');
  const accents={"'":'\u0301','`':'\u0300','^':'\u0302','"':'\u0308','~':'\u0303','=':'\u0304'};
  text=text.replace(/\\(['`^"~=])\s*(?:\{([A-Za-z])\}|([A-Za-z]))/g,(_,accent,a,b)=>(a||b)+accents[accent]).normalize('NFC');
  const style=/\\(?:emph|textit|textbf|textrm|textnormal)\b/g;
  let result='',position=0;
  for(let match;(match=style.exec(text));){
    const group=readGroup(text,style.lastIndex);
    if(!group) continue;
    result+=text.slice(position,match.index)+group.value;
    position=group.end;style.lastIndex=group.end;
  }
  return result+text.slice(position);
}
function decodeEntities(text){
  return text.replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi,(_,entity)=>{
    if(entity[0]==='#'){
      const n=entity[1].toLowerCase()==='x'?parseInt(entity.slice(2),16):Number(entity.slice(1));
      return n<=0x10ffff?String.fromCodePoint(n):'';
    }
    return {amp:'&',lt:'<',gt:'>',quot:'"',apos:"'",nbsp:' '}[entity.toLowerCase()];
  });
}
function scriptText(text, map, prefix){
  return [...text].every(c=>map[c])?[...text].map(c=>map[c]).join(''):prefix+text;
}
function fractionPart(text){
  return [...text].length<=1 || /^\d+(?:\.\d+)?$/.test(text)?text:'('+text+')';
}
// Read only MathML generated by KaTeX, without a browser DOM dependency.
function mathMLText(markup){
  const math=markup.match(/<math\b[\s\S]*?<\/math>/)?.[0]||'';
  const root={tag:'root',children:[]}, stack=[root];
  for(const piece of math.match(/<[^>]+>|[^<]+/g)||[]){
    if(piece.startsWith('</')){if(stack.length>1) stack.pop();continue;}
    if(piece.startsWith('<')){
      const tag=/^<([\w-]+)/.exec(piece)?.[1];
      if(!tag) continue;
      const node={tag,children:[]};
      stack.at(-1).children.push(node);
      if(!piece.endsWith('/>')) stack.push(node);
    }else stack.at(-1).children.push(decodeEntities(piece));
  }
  const read=node=>{
    if(typeof node==='string') return node;
    if(['annotation','annotation-xml','mphantom'].includes(node.tag)) return '';
    const children=node.children.map(read);
    if(node.tag==='msub') return children[0]+scriptText(children[1],subscript,'_');
    if(node.tag==='msup') return children[0]+scriptText(children[1],superscript,'^');
    if(node.tag==='msubsup') return children[0]+scriptText(children[1],subscript,'_')+scriptText(children[2],superscript,'^');
    if(node.tag==='mfrac') return children.map(fractionPart).join('/');
    if(node.tag==='msqrt') return '√('+children.join('')+')';
    if(node.tag==='mroot') return (children[1]||'')+'√('+(children[0]||'')+')';
    if(node.tag==='mspace') return ' ';
    if(node.tag==='mover' && children[1]==='¯') return children[0]+'\u0305';
    return children.join('');
  };
  return read(root).replace(/\s+/g,' ');
}

export function formatScientificMath(source, display=false){
  // Some feeds escape an underscore after APS's empty base group.
  const tex=decodeEntities(source).replace(/(\{\s*\})\\_/g,'$1_');
  const key=(display?'D:':'I:')+tex;
  if(mathCache.has(key)) return mathCache.get(key);
  if(tex.length>MAX_MATH_LENGTH) return {html:null,plain:source};
  try{
    const html=katex.renderToString(tex,{
      displayMode:display, output:'htmlAndMathml', throwOnError:true,
      trust:false, strict:'ignore', maxExpand:200, maxSize:8,
      macros:{'\\mathbit':'\\boldsymbol{#1}'}
    });
    return cachePut(mathCache,key,{html,plain:mathMLText(html)});
  }catch{
    return cachePut(mathCache,key,{html:null,plain:source});
  }
}
export function scientificPlainText(value){
  const text=String(value??'');
  if(textCache.has(text)) return textCache.get(text);
  return cachePut(textCache,text,splitScientificText(text).map(token=>token.type==='text'?displayText(token.value):formatScientificMath(token.value,token.display).plain).join(''));
}
export function scientificSearchText(value){
  return scientificPlainText(value).normalize('NFKC').toLowerCase().replace(/[_^]/g,'');
}
function plainHighlighted(container,text,keywords){
  if(!keywords.length){container.append(document.createTextNode(text));return;}
  const lower=text.toLowerCase(),spans=[];
  for(const keyword of keywords){
    const kw=keyword.toLowerCase();let index=0;
    while(kw && (index=lower.indexOf(kw,index))!==-1){spans.push({start:index,end:index+kw.length});index+=kw.length;}
  }
  spans.sort((a,b)=>a.start-b.start);
  const merged=[];
  for(const span of spans){
    const previous=merged.at(-1);
    if(previous && span.start<=previous.end) previous.end=Math.max(previous.end,span.end);
    else merged.push({...span});
  }
  let index=0;
  for(const span of merged){
    container.append(document.createTextNode(text.slice(index,span.start)));
    const mark=document.createElement('mark');mark.textContent=text.slice(span.start,span.end);container.append(mark);index=span.end;
  }
  container.append(document.createTextNode(text.slice(index)));
}
// Keep a chemical name and its adjacent script fragments on the same line.
// Leave the rest of the prose intact so phrase highlighting still works.
function displayGroups(input){
  const tokens=input.map(token=>({...token})), output=[];
  for(let i=0;i<tokens.length;i++){
    const token=tokens[i];
    if(token.type!=='math' || token.display){output.push(token);continue;}
    const children=[], previous=output.at(-1);
    if(previous?.type==='text'){
      const suffix=/\S+$/.exec(previous.value);
      if(suffix){
        children.push({type:'text',value:suffix[0]});
        previous.value=previous.value.slice(0,suffix.index);
        if(!previous.value) output.pop();
      }
    }
    children.push(token);
    while(i+1<tokens.length){
      const next=tokens[i+1];
      if(next.type==='math' && !next.display){children.push(next);i++;continue;}
      if(next.type!=='text') break;
      const prefix=/^\S+/.exec(next.value);
      if(!prefix) break;
      children.push({type:'text',value:prefix[0]});
      if(prefix[0].length<next.value.length){next.value=next.value.slice(prefix[0].length);break;}
      i++;
    }
    output.push(children.length>1?{type:'cluster',children}:token);
  }
  return output;
}
export function renderScientificText(container,value,keywords=[]){
  const words=keywords.filter(k=>typeof k==='string' && k.trim()).map(k=>k.trim());
  container.textContent='';
  const render=(parent,token)=>{
    if(token.type==='cluster'){
      const group=document.createElement('span');group.className='scientific-cluster';
      token.children.forEach(child=>render(group,child));parent.append(group);return;
    }
    if(token.type==='text'){plainHighlighted(parent,displayText(token.value),words);return;}
    const math=formatScientificMath(token.value,token.display);
    if(!math.html){plainHighlighted(parent,token.raw,words);return;}
    const hit=words.some(word=>scientificSearchText(math.plain).includes(scientificSearchText(word)));
    const span=document.createElement(hit?'mark':'span');
    span.className='scientific-math'+(token.display?' scientific-display':'');
    // This markup is generated by the local renderer with trust=false, never by a feed.
    span.innerHTML=math.html;
    parent.append(span);
  };
  displayGroups(splitScientificText(value)).forEach(token=>render(container,token));
  return container;
}
